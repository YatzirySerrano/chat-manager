<?php

namespace App\Models;

use App\Enums\ConversationOrigin;
use App\Enums\ConversationStatus;
use App\Services\Conversations\ConversationAccess;
use Database\Factories\ConversationFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Carbon;

/**
 * @property int $id
 * @property int $connection_id
 * @property int $contact_id
 * @property int|null $department_id
 * @property int|null $assigned_user_id
 * @property ConversationStatus $status
 * @property-read bool|null $open_lock Generated by MariaDB from `status`.
 * @property Carbon|null $last_message_at
 * @property Carbon|null $last_inbound_at
 * @property Carbon|null $first_response_at
 * @property Carbon|null $last_outbound_at Informative only: replies never extend the customer service window.
 * @property Carbon|null $assigned_at
 * @property Carbon|null $on_hold_at
 * @property string|null $on_hold_reason
 * @property Carbon|null $closed_at
 * @property int|null $closed_by_user_id
 * @property Carbon|null $reopened_at
 * @property int $reopen_count
 * @property int $version Incremented by every operational change, so a decision taken on stale data is detected.
 * @property ConversationOrigin $origin live, or imported from another system (history, never operational).
 * @property Carbon|null $history_only_at Set when an imported conversation was archived as read-only history.
 * @property int|null $imported_by_transfer_id The history import batch that created it.
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
#[Fillable(['connection_id', 'contact_id', 'department_id'])]
class Conversation extends Model
{
    /** @use HasFactory<ConversationFactory> */
    use HasFactory;

    /**
     * The model's default values for attributes.
     *
     * @var array<string, mixed>
     */
    protected $attributes = [
        'status' => 'pending',
        'version' => 0,
        'reopen_count' => 0,
        'origin' => 'live',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'status' => ConversationStatus::class,
            'open_lock' => 'boolean',
            'last_message_at' => 'datetime',
            'last_inbound_at' => 'datetime',
            'last_outbound_at' => 'datetime',
            'first_response_at' => 'datetime',
            'assigned_at' => 'datetime',
            'on_hold_at' => 'datetime',
            'closed_at' => 'datetime',
            'reopened_at' => 'datetime',
            'reopen_count' => 'integer',
            'version' => 'integer',
            'origin' => ConversationOrigin::class,
            'history_only_at' => 'datetime',
        ];
    }

    /**
     * Imported from another system (Whaticket): history, never reopened,
     * never attached to new messages and outside metrics and the window.
     */
    public function isImported(): bool
    {
        return $this->origin !== ConversationOrigin::Live;
    }

    /**
     * Archived as read-only history: also outside the inbox, search,
     * exports and the integration API.
     */
    public function isHistoryOnly(): bool
    {
        return $this->history_only_at !== null;
    }

    /**
     * @return BelongsTo<DataTransfer, $this>
     */
    public function importBatch(): BelongsTo
    {
        return $this->belongsTo(DataTransfer::class, 'imported_by_transfer_id');
    }

    /**
     * The channel connection (e.g. a WhatsApp number). Not named `connection`
     * because that would shadow Eloquent's database connection property.
     *
     * @return BelongsTo<Connection, $this>
     */
    public function channelConnection(): BelongsTo
    {
        return $this->belongsTo(Connection::class, 'connection_id');
    }

    /**
     * @return BelongsTo<Contact, $this>
     */
    public function contact(): BelongsTo
    {
        return $this->belongsTo(Contact::class);
    }

    /**
     * @return BelongsTo<Department, $this>
     */
    public function department(): BelongsTo
    {
        return $this->belongsTo(Department::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function assignee(): BelongsTo
    {
        return $this->belongsTo(User::class, 'assigned_user_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function closedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'closed_by_user_id');
    }

    /**
     * Internal notes. They are never customer messages.
     *
     * @return HasMany<ConversationNote, $this>
     */
    public function notes(): HasMany
    {
        return $this->hasMany(ConversationNote::class);
    }

    /**
     * Provider evidence (e.g. a Meta ad referral) that arrived with this conversation.
     *
     * @return HasMany<ContactAttribution, $this>
     */
    public function attributions(): HasMany
    {
        return $this->hasMany(ContactAttribution::class);
    }

    /**
     * @return HasMany<Message, $this>
     */
    public function messages(): HasMany
    {
        return $this->hasMany(Message::class);
    }

    /**
     * Personal read markers of the people who opened the conversation.
     *
     * @return HasMany<ConversationRead, $this>
     */
    public function reads(): HasMany
    {
        return $this->hasMany(ConversationRead::class);
    }

    /**
     * Personal chat colors users chose for this conversation (each user
     * only ever applies their own).
     *
     * @return HasMany<ChatAppearance, $this>
     */
    public function chatAppearances(): HasMany
    {
        return $this->hasMany(ChatAppearance::class);
    }

    /**
     * @return HasMany<ConversationEvent, $this>
     */
    public function events(): HasMany
    {
        return $this->hasMany(ConversationEvent::class);
    }

    /**
     * @return BelongsToMany<Tag, $this>
     */
    public function tags(): BelongsToMany
    {
        return $this->belongsToMany(Tag::class)->withPivot(['tagged_by_user_id', 'created_at']);
    }

    /**
     * Restrict the query to conversations the user is allowed to see. The
     * rule itself lives in ConversationAccess, shared with the policy.
     *
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function visibleTo(Builder $query, User $user): void
    {
        app(ConversationAccess::class)->restrictToVisible($query, $user);
    }

    /**
     * Conversations attended on the platform (not imported history).
     *
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function live(Builder $query): void
    {
        $query->where($query->qualifyColumn('origin'), ConversationOrigin::Live->value);
    }

    /**
     * Everything but the history archived as read-only (live conversations
     * and imported ones kept as operational history).
     *
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function notHistoryOnly(Builder $query): void
    {
        $query->whereNull($query->qualifyColumn('history_only_at'));
    }

    /**
     * Conversations imported from another system.
     *
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function imported(Builder $query): void
    {
        $query->where($query->qualifyColumn('origin'), '!=', ConversationOrigin::Live->value);
    }

    /**
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function notClosed(Builder $query): void
    {
        $query->where('status', '!=', ConversationStatus::Closed);
    }

    /**
     * Conversations an agent is responsible for (in attention, including
     * legacy on_hold rows not migrated yet).
     *
     * @param  Builder<Conversation>  $query
     */
    #[Scope]
    protected function attended(Builder $query): void
    {
        $query->whereIn('status', ConversationStatus::attending());
    }
}
